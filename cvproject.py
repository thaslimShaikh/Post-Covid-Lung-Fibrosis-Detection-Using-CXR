# ---------------- LIGHTWEIGHT ATTENTION BLOCK ----------------

def cbam_block(inputs):

    # Channel Attention
    avg = GlobalAveragePooling2D()(inputs)
    maxp = GlobalMaxPooling2D()(inputs)

    shared = Dense(64, activation='relu')

    avg = shared(avg)
    maxp = shared(maxp)

    channel = Add()([avg, maxp])
    channel = Dense(inputs.shape[-1], activation='sigmoid')(channel)
    channel = Multiply()([inputs, channel])

    # Spatial Attention
    avg = Lambda(lambda x: tf.reduce_mean(x, axis=-1, keepdims=True))(channel)
    maxp = Lambda(lambda x: tf.reduce_max(x, axis=-1, keepdims=True))(channel)

    spatial = Concatenate()([avg, maxp])
    spatial = Conv2D(1, kernel_size=7, padding='same', activation='sigmoid')(spatial)

    return Multiply()([channel, spatial])



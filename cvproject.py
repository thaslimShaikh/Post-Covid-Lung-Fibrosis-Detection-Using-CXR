import numpy as np
import tensorflow as tf
from tensorflow.keras.applications import ResNet50
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.models import Model
from tensorflow.keras.callbacks import EarlyStopping
from sklearn.metrics import classification_report, roc_auc_score

# CONFIGURATION
DATA_DIR = "/content/processed"
IMG_SIZE = 224
BATCH_SIZE = 16
EPOCHS = 15
LEARNING_RATE = 1e-5   # lower LR for fine-tuning

# LOAD INDICES
train_idx = np.load(f"{DATA_DIR}/train_idx.npy")
test_idx  = np.load(f"{DATA_DIR}/test_idx.npy")
TOTAL_SAMPLES = len(train_idx) + len(test_idx)

# LOAD MEMMAP DATA
X_mm = np.memmap(
    f"{DATA_DIR}/X_all.dat",
    dtype="float32",
    mode="r",
    shape=(TOTAL_SAMPLES, IMG_SIZE, IMG_SIZE, 3)
)

y_mm = np.memmap(
    f"{DATA_DIR}/y_all.dat",
    dtype="int8",
    mode="r",
    shape=(TOTAL_SAMPLES,)
)

# SAMPLE WEIGHTS (REDUCED)
pos = np.sum(y_mm[train_idx])
neg = len(train_idx) - pos

weight_for_0 = 1.0
weight_for_1 = (neg / pos) * 0.5   # reduced impact

print("Sample Weights:")
print("Normal   :", weight_for_0)
print("Fibrosis :", weight_for_1)

# DATA GENERATOR
def data_generator(indices, batch_size=BATCH_SIZE):
    while True:
        np.random.shuffle(indices)
        for i in range(0, len(indices), batch_size):
            batch_idx = indices[i:i + batch_size]
            X_batch = X_mm[batch_idx]
            y_batch = y_mm[batch_idx]
            sw = np.where(y_batch == 1, weight_for_1, weight_for_0)
            yield X_batch, y_batch, sw

# RESNET50 MODEL (PARTIALLY UNFROZEN)
base_model = ResNet50(
    weights="imagenet",
    include_top=False,
    input_shape=(224,224,3)
)

# Unfreeze last 40 layers
for layer in base_model.layers[:-40]:
    layer.trainable = False
for layer in base_model.layers[-40:]:
    layer.trainable = True

x = base_model.output
x = GlobalAveragePooling2D()(x)
x = Dense(256, activation='relu')(x)
x = Dropout(0.4)(x)
output = Dense(1, activation='sigmoid')(x)

model = Model(inputs=base_model.input, outputs=output)
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=LEARNING_RATE),
    loss='binary_crossentropy',
    metrics=['accuracy']
)
print("\nFine-Tuned ResNet50 Model:")
model.summary()

# TRAIN MODEL (WITH EARLY STOPPING)
steps_per_epoch = len(train_idx) // BATCH_SIZE
val_steps = len(test_idx) // BATCH_SIZE
early_stop = EarlyStopping(
    monitor='val_loss',
    patience=3,
    restore_best_weights=True
)
print("\nTraining Fine-Tuned Model...\n")

history = model.fit(
    data_generator(train_idx),
    steps_per_epoch=steps_per_epoch,
    validation_data=data_generator(test_idx),
    validation_steps=val_steps,
    epochs=EPOCHS,
    callbacks=[early_stop]
)

# EVALUATION + THRESHOLD TUNING
print("\nEvaluating Final Model...\n")

y_true, y_prob = [], []

for X_batch, y_batch, _ in data_generator(test_idx):
    preds = model.predict(X_batch)
    y_true.extend(y_batch)
    y_prob.extend(preds)
    if len(y_true) >= len(test_idx):
        break

y_true = np.array(y_true[:len(test_idx)])
y_prob = np.array(y_prob[:len(test_idx)])

# threshold tuning
THRESHOLD = 0.4
y_pred = (y_prob > THRESHOLD).astype(int)
print("Threshold Used:", THRESHOLD)
print("\nClassification Report:")
print(classification_report(y_true, y_pred))
print("ROC-AUC Score:", roc_auc_score(y_true, y_prob))

# SAVE FINAL MODEL
model.save("/content/final_fibrosis_model.keras")
print("\nPhase-2C Completed: Final Optimized Model Saved")

